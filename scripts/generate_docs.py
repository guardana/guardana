"""Generate the factual documentation fragments from the installed registry.

Every count this project states in prose has drifted at least once: the landing
page advertised 25 rules across three releases that took the number to 32, and
the README's roadmap table still called 0.6 "27 rules" while describing 0.4's
work. Hand-maintained facts about a growing registry do not stay true — so they
stop being hand-maintained.

    python scripts/generate_docs.py            # write docs/generated/*.md
    python scripts/generate_docs.py --check    # exit 1 if any file is stale

`release.py` runs the first; `test_generated_docs.py` runs the second, so a rule
added between releases turns the suite red rather than waiting for someone to cut
one. Prose links to these files instead of repeating them.
"""

