"""Nav metadata for the generated pages, alongside the code that writes them.

The hand-written pages carry their own frontmatter, and the site build refuses a
page without a title rather than inferring one from the filename. These pages have
no author to write it, so it lives here — beside the renderer, in the same file a
new generated page would be added to.
"""


def _front(name: str) -> str:
    title, nav_order, summary = _FRONTMATTER[name]
    return (
        f"---\ntitle: {title}\nnav_order: {nav_order}\n"
        f'summary: "{summary}"\nstatus: stable\n---\n\n'
    )


def _rules() -> list[Rule]:
    return sorted(provide_rules(), key=lambda r: r.meta.id)


def _summary(rules: list[Rule]) -> str:
    by_surface = Counter(r.meta.surface for r in rules)
    by_kind = Counter(r.meta.target_kind for r in rules)
    by_severity = Counter(r.meta.severity for r in rules)
    lines = [
        _HEADER,
        f"**{len(rules)} built-in rules** ship with `guardana-rules` {__version__}.\n",
        "| Facet | Count |",
        "|---|---:|",
        f"| Build-time (`scan`) | {by_surface[Surface.BUILD]} |",
        f"| Runtime (`probe`, `monitor`) | {by_surface[Surface.RUNTIME]} |",
        f"| Against artifacts | {by_kind[TargetKind.ARTIFACT]} |",
        f"| Against endpoints | {by_kind[TargetKind.ENDPOINT]} |",
    ]
    lines += [
        f"| Severity {severity.name} | {by_severity[severity]} |"
        for severity in sorted(Severity, reverse=True)
        if by_severity[severity]
    ]
    ctx = RuleContext(evaluators={type(e).id: e for e in provide_evaluators()})
    proven = sum(verify_rule(rule, ctx).is_proven for rule in rules)
    lines.append(f"| Proven by their own finding, clean and inconclusive samples | {proven} |")
    return "\n".join(lines) + "\n"


def _catalog(rules: list[Rule]) -> str:
    lines = [
        _HEADER,
        "Every built-in rule, its severity, the surface it runs on, the kind of",
        "target it reads, its maturity, and the frameworks it maps to. A rule",
        "without a mapping does not ship.\n",
        "| Rule | Severity | Surface | Target | Maturity | Maps to |",
        "|---|---|---|---|---|---|",
    ]
    for rule in rules:
        meta = rule.meta
        taxonomy = ", ".join(f"`{t.reference}`" for t in meta.taxonomy) or "—"
        lines.append(
            f"| `{meta.id}` | {meta.severity.name} | {meta.surface.value} "
            f"| {meta.target_kind} | {meta.maturity} | {taxonomy} |"
        )
    return "\n".join(lines) + "\n"


def _evaluators() -> str:
    always = {type(e).id: type(e) for e in provide_evaluators()}
    configured: dict[str, type[Evaluator]] = {kind.id: kind for kind in CONFIG_WIRED}
    lines = [
        _HEADER,
        "An evaluator turns a model's reply into a verdict with a confidence.",
        "A rule names one by id, so swapping graders never touches the rule.\n",
        "| Evaluator | Available | What it grades on | Error correction |",
        "|---|---|---|---|",
    ]
    lines += [_evaluator_row(name, "always", kind) for name, kind in sorted(always.items())]
    lines += [
        _evaluator_row(name, "when configured", kind) for name, kind in sorted(configured.items())
    ]
    return "\n".join(lines) + "\n"


def _evaluator_row(name: str, available: str, kind: type[Evaluator]) -> str:
    correction = "Not needed" if kind.deterministic is True else "With matching calibration"
    return f"| `{name}` | {available} | {_first_line(kind.__doc__ or '')} | {correction} |"


def _taxonomy(rules: list[Rule]) -> str:
    per_framework: defaultdict[str, set[str]] = defaultdict(set)
    for rule in rules:
        for ref in rule.meta.taxonomy:
            per_framework[ref.framework].add(ref.id)
    lines = [
        _HEADER,
        "Which entries of each framework at least one built-in rule maps to.",
        "Coverage of an entry is not a claim that the entry is fully addressed —",
        "See [detection limits](detection-limits.md) for what each rule proves.\n",
        "| Framework | Entries covered |",
        "|---|---|",
    ]
    for framework in sorted(per_framework):
        entries = ", ".join(f"`{e}`" for e in sorted(per_framework[framework]))
        lines.append(f"| {framework} | {entries} |")
    return "\n".join(lines) + "\n"


def _first_line(doc: str) -> str:
    return doc.strip().splitlines()[0].strip() if doc.strip() else "—"


RULES_JSON_SCHEMA_VERSION = 1
"""Version of `rules.json`, because a generated document is still a document.

Regenerating it is free, so this is not about migration — it is about a consumer
being able to tell which shape it is holding. The rule explorer on the site is one
such consumer; a team rendering their own explorer over their own pack is the
other, and that one is not in this repository.
"""


def _family(rule_id: str) -> str:
    """Take the part of an id that groups rules a reader thinks about together.

    `guardana.supply_chain.pickle_opcode` is supply chain; `acme.agent.customer_data`
    is agent. Taken from the id rather than declared, because the id is what a
    profile's include/exclude globs already select on — a second, declared grouping
    could disagree with the one people actually filter by.
    """
    parts = rule_id.split(".")
    return parts[1] if len(parts) > 1 else parts[0]


def _goal(rule: Rule) -> str | None:
    """Read the sentence a rule's own expectation gives for what a secure answer looks like.

    Taken from `declared_expectations()`, which is the public contract, so a third
    party's pack renders the same way. A rule that grades entirely in Python
    declares no expectation and gets `null` here — not an empty string and not a
    docstring scraped off its class, because several rules share one class and the
    explorer would then attribute one rule's reasoning to another.
    """
    for _evaluator_id, expectation in rule.declared_expectations():
        goal = getattr(expectation, "goal", None)
        if isinstance(goal, str) and goal.strip():
            return goal.strip()
    return None


def _rule_entry(rule: Rule) -> dict[str, object]:
    meta = rule.meta
    return {
        "id": meta.id,
        "namespace": meta.id.split(".")[0],
        "family": _family(meta.id),
        "title": meta.title,
        "severity": meta.severity.name,
        "surface": meta.surface.value,
        "target_kind": str(meta.target_kind),
        "evaluator": meta.evaluator,
        "impact": str(meta.impact),
        "destructive": meta.destructive,
        "maturity": str(meta.maturity),
        "detection": str(meta.detection),
        "requires": sorted(str(capability) for capability in meta.required_capabilities),
        "estimated_requests": rule.estimated_requests,
        "goal": _goal(rule),
        "taxonomy": [
            {
                "reference": ref.reference,
                "framework": ref.framework,
                "id": ref.id,
                "title": ref.title,
                "rank": ref.rank,
            }
            for ref in meta.taxonomy
        ],
    }


def _rules_json(rules: list[Rule]) -> str:
    """Render the same registry walk as `rule-catalog.md`, for a build rather than a reader.

    The markdown table answers "what ships" in six columns because that is what a
    page of prose can carry. The site's rule explorer needs the other facets too —
    what a rule costs, what it does to the target, which capabilities it needs —
    and inventing a second walk to get them is how the explorer would start
    disagreeing with the catalogue. One walk, two renderings; a test pins them to
    each other.
    """
    return (
        json.dumps(
            {
                "schema_version": RULES_JSON_SCHEMA_VERSION,
                "generated_by": "scripts/generate_docs.py from the installed registry — "
                "do not edit by hand",
                "guardana_version": __version__,
                "rules": [_rule_entry(rule) for rule in rules],
            },
            indent=2,
        )
        + "\n"
    )


