def _pack_manifest(rules: list[Rule]) -> str:
    """Render the built-in pack's own manifest from the registry.

    Generated, not hand-written, and that is the whole point: `provides:` is a list
    of every id this pack registers, and a hand-maintained copy of 51 ids is the
    shape of every stale claim this repository has had to fix. A third party writes
    theirs by hand because theirs is short; ours is long, so ours comes from the
    registry and `pack validate` compares the two.
    """
    evaluators = sorted(e.id for e in provide_evaluators())
    return (
        "# Generated by scripts/generate_docs.py — do not edit.\n"
        "#\n"
        "# The manifest for Guardana's own rule pack, which goes through the third\n"
        "# party's door on purpose: a validator this repository exempted itself from\n"
        "# would be a bar we ask other people to clear alone, and the first drift it\n"
        "# would stop catching is our own.\n"
        "#\n"
        "# `provides:` is generated from the registry rather than typed, because a\n"
        "# hand-maintained list of this length is how every stale count here began.\n"
        "# `guardana pack validate` compares it against what the entry points really\n"
        "# register, so a rule renamed in one place and not the other fails the build.\n"
        "#\n"
        "# Documentation: docs/usage-pack.md\n"
        "\n"
        f"schema_version: {_BUILT_IN_MANIFEST_SCHEMA}\n"
        "name: guardana-rules\n"
        "\n"
        "# Versioned separately from the product: in 0.x the product's minor breaks API\n"
        "# by design, and a pack pinned to a product range would need re-releasing on\n"
        "# every minor even when nothing it touches moved.\n"
        'extension_api: ">=1,<2"\n'
        "\n"
        "description: >\n"
        "  The built-in rules: model and dependency supply chain, prompt and jailbreak\n"
        "  probes, agent and MCP checks, and the trace rules that grade a recorded\n"
        "  execution. Every rule maps to a public framework.\n"
        "\n"
        "provides:\n"
        "  rules:\n"
        + "".join(f"    - {rule.meta.id}\n" for rule in sorted(rules, key=lambda r: r.meta.id))
        + "  evaluators:\n"
        + "".join(f"    - {name}\n" for name in evaluators)
    )


def main() -> int:
    """Write the generated fragments, or report which are stale."""
    parser = argparse.ArgumentParser(description="Generate documentation from the registry.")
    parser.add_argument("--check", action="store_true", help="exit 1 if stale; write nothing")
    args = parser.parse_args()

    _OUT.mkdir(parents=True, exist_ok=True)
    rules = _rules()
    stale: list[str] = []
    for name, render in _FILES.items():
        path = _OUT / name
        wanted = render(rules)
        if name in _FRONTMATTER:
            wanted = _front(name) + wanted
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == wanted:
            continue
        stale.append(name)
        if not args.check:
            path.write_text(wanted, encoding="utf-8")

    manifest = _pack_manifest(rules)
    if _PACK_MANIFEST.read_text(encoding="utf-8") != manifest:
        stale.append("guardana-pack.yaml")
        if not args.check:
            _PACK_MANIFEST.write_text(manifest, encoding="utf-8")

    if not stale:
        print("docs/generated is current")
        return 0
    if args.check:
        print("docs/generated is out of date: " + ", ".join(stale))
        print("run `uv run python scripts/generate_docs.py` to refresh it")
        return 1
    print("regenerated: " + ", ".join(stale))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
